#!/usr/bin/env python3
"""Spec-neutral replay of source IF at an original foreground dispatch token.

Consumes existing *same native run* raw log and original pinned SimC profile;
no C++ recompilation and no speculative reconstruction of missing state.
Independent AST reads only explicitly source-scoped PRE adapter fields. It
does NOT accept a native IF comparator, selected spell, or later JSON2 action
as input to IF truth, physical readiness or competitor priority.

A source adapter scoped to one class cannot silently become another class's
PRE evidence even when both were generated by the same instrumented binary.
This audit reuses the existing original dispatch, return/emitter and AST code.
"""
from __future__ import annotations

import argparse
from collections import Counter
from hashlib import sha256
import json
import math
from pathlib import Path
import re

from simc_apl_semantic_ir_v2 import (
    parse_profile, evaluate_ast, truth, canonical, git_blob, AplError
)
from general_rotation_original_foreground_dispatch_v1 import (
    inspect_log, BEGIN, SELECT, CALLSITE, SEL, NATIVE, DispatchError,
    SCHEMA as DISPATCH_SCHEMA
)
from general_rotation_same_run_return_emitter_v1 import (
    parse as parse_emitters, POLICY, SIMC_COMMIT
)
from simc_original_select_if_pre_witness_v1 import plan_check

SCHEMA="ZrotOriginalSimCSelectedDispatchSourceIFBoundedReplayV1"
RECEIPT_SCHEMA="ZrotGenericOriginalForegroundDispatchCausalReceiptV1"
UNIQUE="ORIGINAL_APL_FOREGROUND_SELECT_TO_JSON2_CALLSITE_PROVEN"
UNKNOWN="UNKNOWN"
HEX64=re.compile(r"^[0-9a-f]{64}$")
PTR=re.compile(r"^0x[0-9a-fA-F]+$")


class DispatchIFError(ValueError):
    pass


def require(test:bool, code:str)->None:
    if not test:
        raise DispatchIFError(code)


def sha(raw:bytes)->str:
    return sha256(raw).hexdigest()


def duplicate_free(pairs):
    out={}
    for k,v in pairs:
        require(k not in out,"DUPLICATE_PINNED_JSON_KEY")
        out[k]=v
    return out


def load(path:Path)->tuple[dict,bytes]:
    require(path.is_file() and not path.is_symlink(),
            "MISSING_OR_SYMLINKED_INPUT")
    blob=path.read_bytes()
    require(0<len(blob)<10_000_000,"UNBOUNDED_OR_EMPTY_INPUT")
    result=json.loads(blob,object_pairs_hook=duplicate_free)
    require(isinstance(result,dict),"INVALID_JSON_ROOT")
    return result,blob


def _profile_class(raw:bytes)->str|None:
    """Source profile actor type; never infer from selected action name."""
    text=raw.decode("utf-8")
    found=re.findall(r'(?m)^([a-z][a-z0-9_]*)="[^"\n]*"\s*$',text)
    return found[0] if len(found)==1 else None


def _adapter_class(plan:dict)->str|None:
    # External class C++ path is from a source-pinned checked plan. The same
    # literal class must occur in the actual profile. No class-specific code.
    path=plan.get("class_cpp")
    if not isinstance(path,str):
        return None
    match=re.fullmatch(r"engine/class_modules/sc_([a-z][a-z0-9_]*)\.cpp",path)
    return match.group(1) if match else None


def replay(log:str,profile:bytes,plan:dict,*,source_label:str,
           targets:int,expected_dispatch_sha256:str|None=None,
           first_window_ms:int=10000)->dict:
    require(type(source_label) is str and bool(source_label) and
            type(targets) is int and 1<=targets<=8 and
            type(first_window_ms) is int and 1000<=first_window_ms<=30000,
            "ORIGINAL_REPLAY_SCOPE_INVALID")
    plan_check(plan)
    require(plan["source_revision"]==SIMC_COMMIT,
            "ADAPTER_ORIGINAL_REVISION_MISMATCH")
    parsed=parse_profile(profile,require_source=False)
    if expected_dispatch_sha256 is not None:
        require(HEX64.fullmatch(expected_dispatch_sha256) is not None,
                "EXPECTED_DISPATCH_SHA256_REQUIRED")
    try:
        previous=inspect_log(log)
    except DispatchError as e:
        raise DispatchIFError("PREVIOUS_ORIGINAL_DISPATCH_PROOF_INVALID") from e
    require(previous["schema"]==DISPATCH_SCHEMA and
            previous["source_evidence_level"]==
                "PINNED_ACTUAL_CPP_FOREGROUND_APL_SELECT_TO_JSON2_CALLSITE" and
            previous["original_simc_revision"]==SIMC_COMMIT and
            previous["physical_action_execute_event_proven"] is False and
            previous["complete_source_physical_READY_proven"]==0 and
            previous["WCL_blind_holdout"]=="NOT_RUN",
            "PREVIOUS_ORIGINAL_DISPATCH_BOUNDARY_DRIFT")
    source_sha=sha(canonical(previous))
    if expected_dispatch_sha256 is not None:
        require(source_sha==expected_dispatch_sha256,
                "PINNED_REAL_ORIGINAL_DISPATCH_SHA256_CHANGED")
    _,emit=parse_emitters(log)
    require(len(emit)==previous["emitter_total"] and
            len(previous["sample"])==len(emit),
            "ORIGINAL_EMITTER_SEQUENCE_TRUNCATED")
    phase_index={(x["kind"],x["ordinal"]):x for x in emit}
    lines=log.splitlines()
    begins={}; selected={}; callsites={}; pres={};native={}
    for number,line in enumerate(lines):
        if BEGIN in line:
            p=line.split(BEGIN,1)[1].strip().split("|")
            require(len(p)==3 and p[0].isdecimal() and
                    p[1].isdecimal() and int(p[1])>0 and
                    PTR.fullmatch(p[2]) is not None,"BEGIN_MARKER_MALFORMED")
            token=int(p[1]); require(token not in begins,"REUSED_APL_TOKEN")
            begins[token]=(number,int(p[0]),p[2].lower())
        if SELECT in line:
            p=line.split(SELECT,1)[1].strip().split("|")
            require(len(p)==4 and p[0].isdecimal() and
                    p[1].isdecimal() and int(p[1])>0 and
                    all(PTR.fullmatch(s) is not None for s in p[2:]),
                    "SELECT_MARKER_MALFORMED")
            token=int(p[1]);require(token not in selected,"SELECT_TOKEN_DUPLICATE")
            selected[token]=(number,int(p[0]),p[2].lower(),p[3].lower())
        if CALLSITE in line:
            p=line.split(CALLSITE,1)[1].strip().split("|")
            require(len(p)==6 and p[0].isdecimal() and
                    p[1].isdecimal() and int(p[1])>0 and
                    p[2] in ("APL_ROOT","NON_APL_FOREGROUND") and
                    PTR.fullmatch(p[3]) is not None and
                    PTR.fullmatch(p[4]) is not None and p[5].isdecimal(),
                    "CALLSITE_MARKER_MALFORMED")
            key=("C",int(p[5]));require(key not in callsites,"CALLSITE_REUSED_ORDINAL")
            callsites[key]=(number,int(p[0]),int(p[1]),p[2],
                            p[3].lower(),p[4].lower())
        if SEL in line:
            p=line.split(SEL,1)[1].strip().split("|")
            require(len(p)==7 and p[0].isdecimal() and
                    p[1].isdecimal() and int(p[1])>0 and
                    p[3].isdecimal() and PTR.fullmatch(p[4]) is not None and
                    re.fullmatch(r"-?\d+",p[6]) is not None,
                    "SELECT_CALL_PRE_MALFORMED")
            try:
                resource=float(p[5])
            except (TypeError,ValueError,OverflowError) as e:
                raise DispatchIFError("ORIGINAL_PRE_RESOURCE_NONNUMERIC") from e
            require(math.isfinite(resource),"ORIGINAL_PRE_RESOURCE_NONFINITE")
            call=int(p[1]);require(call not in pres,"SELECT_PRE_ID_REUSED")
            pres[call]=(number,int(p[0]),p[2],int(p[3]),
                        p[4].lower(),resource,int(p[6]))
        if NATIVE in line:
            p=line.split(NATIVE,1)[1].strip().split("|")
            require(len(p)==4 and p[0].isdecimal() and
                    p[1].isdecimal() and int(p[1])>0 and
                    PTR.fullmatch(p[2]) is not None and p[3] in ("0","1"),
                    "NATIVE_IF_MARKER_MALFORMED")
            key=(int(p[1]),p[2].lower())
            require(key not in native,"DUPLICATE_NATIVE_CALL_IF")
            native[key]=(number,int(p[0]),bool(int(p[3])))
    require(len(begins)>=len(selected) and
            len(selected)>=previous["path_counts"].get(UNIQUE,0),
            "ROOT_FOREGROUND_DISPATCH_MARKERS_INCOMPLETE")
    source_class=_profile_class(profile)
    adapter_class=_adapter_class(plan)
    adapter_applies=(source_class is not None and
                     adapter_class is not None and source_class==adapter_class)
    counts=Counter(); phase=Counter();first=Counter()
    missing_symbols=Counter();examples=[];unlinked=[]
    for index,record in enumerate(emit):
        source_key=(record["kind"],record["ordinal"])
        old=previous["sample"][index]
        require((old["phase"],old["JSON2_ordinal"])==source_key and
                old["t_ms"]==record["t_ms"] and
                old["source_APL_list"]==record["owner"] and
                old["source_APL_rank"]==record["rank_one_based"],
                "DISPATCH_EVENT_TO_SOURCE_EMITTER_ORDER_DRIFT")
        site=callsites.get(source_key)
        known=old["source_attribution"]==UNIQUE
        require(known==(site is not None and site[3]=="APL_ROOT"),
                "ORIGINAL_APL_SOURCE_SITE_PARTITION_CHANGED")
        if not known:
            kind=("PRECOMBAT_SEPARATE_ORIGINAL_EXECUTION_PATH"
                  if record["kind"]=="P"
                  else "UNKNOWN_NON_FOREGROUND_COMBAT_EXECUTION_PATH")
            counts[kind]+=1
            phase[record["kind"]]+=1
            if record["kind"]=="C":
                unlinked.append({
                    "t_ms":record["t_ms"],"JSON2_ordinal":record["ordinal"],
                    "source_action":record["action_name"],
                    "source_list":record["owner"],
                    "source_rank":record["rank_one_based"],
                    "missing_route":"UNKNOWN",
                    "real_WoW_action":"UNKNOWN"})
            continue
        seq,t_call,token,route,actor,pointer=site
        start=begins.get(token)
        returned=selected.get(token)
        require(start is not None and returned is not None and
                start[0]<returned[0]<seq<record["index"] and
                start[2]==returned[2]==actor==record["actor"] and
                returned[3]==pointer==record["ptr"] and
                start[1]<=returned[1]<=t_call==record["t_ms"],
                "FOREIGN_OR_FUTURE_ORIGINAL_SELECTED_ACTION")
        if record["rank_one_based"]==0:
            require(False,"CAUSAL_SELECTED_SOURCE_WITHOUT_SOURCE_ROW")
        name=record["owner"]; rank=record["rank_one_based"]
        require(name in parsed["action_lists"] and
                1<=rank<=len(parsed["action_lists"][name]),
                "SOURCE_PROFILE_ROW_IDENTITY_NOT_FOUND")
        row=parsed["action_lists"][name][rank-1]
        # Reuse original exact-call matching; each currently proven case has
        # exactly one selected same-row source-PRE marker before root return.
        matches=[(id_,v) for id_,v in pres.items() if
                 start[0]<v[0]<returned[0] and
                 v[4]==pointer and v[2]==name and v[3]==rank]
        require(len(matches)==1,
                "SELECTED_SOURCE_PRE_EXACT_CALL_AMBIGUOUS_OR_MISSING")
        call_id,pre=matches[0]
        require(start[1]<=pre[1]<=returned[1],
                "SOURCE_PRE_NOT_IN_SELECTED_CALL_TIME")
        native_g=native.get((call_id,pointer))
        if native_g is not None:
            require(pre[0]<native_g[0]<returned[0] and
                    pre[1]==native_g[1],
                    "NATIVE_IF_DIFFERENT_ORIGINAL_CALL_OR_TIME")
        expressions=row["expression_fields"]
        source_if=expressions.get("if")
        facts={}
        if adapter_applies:
            facts[plan["resource_symbol"]]=pre[5]
            if pre[6]>=0:
                facts[plan["buff_symbol"]]=float(pre[6]>0)
        if source_if is None:
            verdict="SOURCE_APL_NO_EXPLICIT_IF_NOT_READY_PROOF"
            result=None
            symbols=[]
        else:
            symbols=source_if["symbols"]
            result=truth(evaluate_ast(source_if["ast"],facts))
            if result is None:
                verdict="UNKNOWN_SOURCE_IF_MISSING_VALID_ORIGINAL_PRE"
                for s in symbols:
                    if s not in facts:missing_symbols[s]+=1
            elif native_g is None:
                verdict="SOURCE_IF_REPLAY_KNOWN_NATIVE_COMPARATOR_NOT_REACHED"
            else:
                require(result==native_g[2],
                        "INDEPENDENT_SOURCE_IF_CONFLICTS_WITH_NATIVE_COMPARATOR")
                verdict="SOURCE_IF_REPLAY_MATCH_ORIGINAL_NATIVE_SAME_CALL"
        counts[verdict]+=1
        phase["C"]+=1
        if record["t_ms"]<first_window_ms:
            first[verdict]+=1
        examples.append({
            "t_ms":record["t_ms"],"JSON2_ordinal":record["ordinal"],
            "source_list":name,"source_rank":rank,
            "source_row_sha256":row["source_sha256"],
            "source_action":row["action"],
            "source_if":source_if["source"] if source_if else None,
            "source_if_symbols":symbols,
            "independent_original_PRE_adapter_applied":adapter_applies,
            "source_IF_independent_truth":
                ("UNKNOWN" if result is None else
                 "TRUE" if result else "FALSE"),
            "native_IF_same_call_comparator":
                ("NOT_REACHED" if native_g is None else
                 "TRUE" if native_g[2] else "FALSE"),
            "replay_verdict":verdict,
            "original_selected_same_call_id":call_id,
            "exact_original_dispatch_token":token,
            "selected_to_JSON2_callsite_proven":True,
            "full_action_READY_proven":False,
            "competing_skills_ready":"UNKNOWN",
            "user_dummy_wrong_skill":"UNKNOWN",
        })
    require(sum(counts.values())==len(emit) and
            phase["C"]==len([x for x in emit if x["kind"]=="C"]) and
            phase["P"]==len([x for x in emit if x["kind"]=="P"]) and
            len(examples)==previous["path_counts"][UNIQUE],
            "PINNED_EMITTER_REPLAY_COVERAGE_CHANGED")
    expected_if=previous["original_selected_IF_witness_counts"]
    comparator_rows=sum(x["native_IF_same_call_comparator"]!="NOT_REACHED"
                        for x in examples)
    no_comparator_rows=len(examples)-comparator_rows
    require(comparator_rows==
             expected_if.get("SELECTED_SAME_CALL_NATIVE_IF_COMPARATOR_ONLY",0)
             and no_comparator_rows==
             expected_if.get("SELECTED_SAME_CALL_PRE_NATIVE_IF_NOT_REACHED",0),
            "ORIGINAL_SAME_CALL_NATIVE_IF_PARTITION_CHANGED")
    return {
      "schema":SCHEMA,"policy_id":POLICY,
      "source_SimC_commit":SIMC_COMMIT,
      "source_spec_label":source_label,"target_count":targets,
      "profile_git_blob":git_blob(profile),
      "source_adapter_class":adapter_class,
      "source_profile_class":source_class,
      "source_PRE_adapter_applies":adapter_applies,
      "original_dispatch_replay_sha256":source_sha,
      "source_of_IF_truth":"SOURCE_TYPED_AST_AND_ORIGINAL_SAME_CALL_PRE_ONLY",
      "actual_original_emitter_records":len(emit),
      "original_foreground_selected_direct_count":len(examples),
      "phase_counts":dict(sorted(phase.items())),
      "source_IF_triage_counts":dict(sorted(counts.items())),
      "first_window_ms_not_verified_opener_end":first_window_ms,
      "first_window_CXX_source_IF_triage_counts":dict(sorted(first.items())),
      "missing_source_IF_symbols": [
          {"symbol":key,"unknown_selected_original_rows":value}
          for key,value in sorted(missing_symbols.items(),
                                  key=lambda x:(-x[1],x[0]))],
      "source_IF_exact_selected_rows":examples,
      "non_foreground_combat_emitter_rows":unlinked,
      "native_IF_same_call_comparator_used_as_input":False,
      "native_IF_comparator_count":comparator_rows,
      "native_IF_not_reached_count":no_comparator_rows,
      "full_physical_READY_proven":0,
      "source_priority_competitors_proven":0,
      "actual_action_execute_completion_proven":False,
      "ST_2T_AoE_general_priority_verified":False,
      "opener_termination":"UNKNOWN","WCL_blind_holdout":"NOT_RUN",
      "dummy_wrong_cast":"UNKNOWN","new_native_CXX_builds":0,
      "WCL_API_calls":0,"MAIN_promoted":False,
    }


def selftest()->dict:
    # Reuse the exact synthetic marker contracts of the original producer.
    profile=(b'warrior="Synthetic"\nspec=fury\n'
             b'actions=/synthetic,if=rage>80&buff.recklessness.up\n')
    mage=(b'mage="Synthetic"\nspec=arcane\n'
          b'actions=/synthetic,if=rage>80&buff.recklessness.up\n')
    from general_rotation_same_run_return_emitter_v1 import (
        RETURN, ACTOR, EMITTER_MARK
    )
    marker="\n".join((
      BEGIN+"100|1|0x11",
      SEL+"100|21|default|1|0xaa|92|1",
      NATIVE+"100|21|0xaa|1",
      RETURN+"100|DIRECT|0x11|default|default|1|0xaa|1",
      SELECT+"100|1|0x11|0xaa",
      CALLSITE+"100|1|APL_ROOT|0x11|0xaa|0",
      ACTOR+"100|C|0|0x11|0xaa",
      EMITTER_MARK+"100|C|0|synthetic|default|1|0xaa"
    ))
    plan={"schema":"ZrotOriginalSimCSourceIFPreSpecAdapterV1",
          "policy_id":POLICY,"source_revision":SIMC_COMMIT,
          "resource_enum":"RESOURCE_RAGE","resource_symbol":"rage",
          "buff_name":"recklessness","buff_symbol":"buff.recklessness.up",
          "class_cpp":"engine/class_modules/sc_warrior.cpp",
          "original_class_cpp_blob":"38ee3dd0d5943eb9227ec55aefb21e7d47244f96",
          "source_expected_buff_construction":
             'make_buff( this, "recklessness"',
          "approved_source_only_nongame_capture":True}
    good=replay(marker,profile,plan,source_label="synthetic",targets=1)
    assert good["original_foreground_selected_direct_count"]==1
    assert good["source_IF_triage_counts"][
        "SOURCE_IF_REPLAY_MATCH_ORIGINAL_NATIVE_SAME_CALL"]==1
    assert good["source_IF_exact_selected_rows"][0][
        "source_IF_independent_truth"]=="TRUE"
    assert good["full_physical_READY_proven"]==0
    other=replay(marker,mage,plan,source_label="another",targets=1)
    assert other["source_PRE_adapter_applies"] is False
    assert other["source_IF_triage_counts"][
        "UNKNOWN_SOURCE_IF_MISSING_VALID_ORIGINAL_PRE"]==1
    assert other["source_IF_exact_selected_rows"][0][
        "source_IF_independent_truth"]=="UNKNOWN"
    n=0
    for broken in (
       marker.replace("0xaa|92|1","0xaa|5|1"),
       marker.replace(NATIVE+"100|21|0xaa|1",NATIVE+"100|21|0xaa|0"),
       marker.replace(SEL+"100|21|default|1|0xaa|92|1",""),
       marker.replace("ZROT_GR_FOREGROUND_APL_RETURN_V1|100|1|0x11|0xaa",
                      "ZROT_GR_FOREGROUND_APL_RETURN_V1|100|1|0x11|0xbb"),
       marker.replace("0x11|0xaa|0","0x12|0xaa|0"),
       marker.replace("0xaa|92|1","0xaa|nan|1"),
       marker.replace("ZROT_GR_FOREGROUND_APL_BEGIN_V1|100|1|0x11",""),
    ):
        try:replay(broken,profile,plan,source_label="synthetic",targets=1)
        except (DispatchIFError,DispatchError):n+=1
        else:raise AssertionError("UNVERIFIED_ORIGINAL_SOURCE_PRE_ACCEPTED")
    return {"schema":SCHEMA,"status":"PASS_SYNTHETIC_OFFLINE",
            "negative_controls":n,"cross_source_adapter_test":True,
            "actual_original_CXX_builds":0,"WCL_API_calls":0,
            "full_ready_proven":0,"dummy_wrong_skill_proven":0}


def main()->None:
    cli=argparse.ArgumentParser(description=__doc__)
    cli.add_argument("--native-log",type=Path)
    cli.add_argument("--original-profile",type=Path)
    cli.add_argument("--source-adapter",type=Path)
    cli.add_argument("--source-label")
    cli.add_argument("--targets",type=int)
    cli.add_argument("--expected-original-dispatch-sha256")
    cli.add_argument("--first-window-ms",type=int,default=10000)
    cli.add_argument("--out",type=Path)
    args=cli.parse_args()
    if all(v is None for k,v in vars(args).items()
           if k!="first_window_ms"):
        print(json.dumps(selftest(),sort_keys=True))
        return
    require(all((args.native_log,args.original_profile,args.source_adapter,
                 args.source_label,args.targets,
                 args.expected_original_dispatch_sha256,args.out)),
            "PINNED_ORIGINAL_NATIVE_REPLAY_ARGUMENTS_REQUIRED")
    plan,_=load(args.source_adapter)
    blob=args.original_profile.read_bytes()
    result=replay(args.native_log.read_text("utf-8"),blob,plan,
                  source_label=args.source_label,targets=args.targets,
                  expected_dispatch_sha256=
                    args.expected_original_dispatch_sha256,
                  first_window_ms=args.first_window_ms)
    args.out.parent.mkdir(parents=True,exist_ok=True)
    with args.out.open("xb") as handle:handle.write(canonical(result))
    print("ORIGINAL_DISPATCH_SOURCE_IF_REPLAY_SHA256="+sha(
        args.out.read_bytes()))
    print("SOURCE_IF_REPLAY_COUNTS="+json.dumps(
        result["source_IF_triage_counts"],sort_keys=True))
    print("SOURCE_ADAPTER_APPLIED="+str(result["source_PRE_adapter_applies"]))
    print("UNKNOWN_NON_FOREGROUND_COMBAT_EMITTER_ROWS="+json.dumps(
        result["non_foreground_combat_emitter_rows"],sort_keys=True))


if __name__=="__main__":
    main()
