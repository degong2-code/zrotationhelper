#!/usr/bin/env python3
"""Strict PRE IF-operand gap auditor for real SimC source decision roots.

No assertion of a live IF truth from timestamp+APL-row joins. Legacy Fury
IF operand receipts have source row/time/name but lack the unique original
action_ready root call ID: they are not attributable to exact decision roots.
Actual native return values are comparison-only and never used as operands.

This module extracts exact root-scoped *requests* and, in synthetic contract
tests only, verifies strict transition time (< action time), row identity,
numeric values and independent three-valued APL evaluation. Production output
cannot certify a fact until a separately validated original-source root-PRE
producer is delivered. The existing observed Native source IR is replayed,
not regenerated by a new SimC run.
"""
from __future__ import annotations

import argparse
from collections import Counter, defaultdict
import json
import math
from pathlib import Path
import re

from general_rotation_original_pre_capture_engine_v1 import canonical
from general_rotation_source_eligibility_decision_ir_v1 import POLICY
from general_rotation_time_scoped_priority_ir_v1 import SCHEMA as TEMPORAL_SCHEMA
from simc_apl_semantic_ir_v2 import (
    evaluate_ast, git_blob, parse_profile, truth,
)

SCHEMA="ZrotGeneralRotationStrictPreIFRootGapAuditV1"
SCHEMA_RECEIPT="ZrotGeneralRotationStrictPreIFRootST2TComparisonV1"
STATUS_UNKNOWN="UNKNOWN_STRICT_PRE_ROOT_OPERANDS_UNOBSERVED"
HEX64=re.compile(r"[0-9a-f]{64}\Z")


class StrictPreGapError(ValueError):
    pass


def _trusted_root_facts(record, *, root_id, row_hash, at_ms, symbols):
    """Validate a *synthetic* root witness; no production adapter yet."""
    if (not isinstance(record,dict) or
        record.get("root_call_id")!=root_id or
        record.get("source_row_sha256")!=row_hash or
        record.get("action_at_simc_ms")!=at_ms or
        record.get("origin")!="SYNTHETIC_SOURCE_ROOT_PRE_FIXTURE"):
        raise StrictPreGapError("EXACT_SOURCE_ROOT_WITNESS_IDENTITY_REQUIRED")
    facts=record.get("facts")
    if not isinstance(facts,dict) or set(facts)-set(symbols):
        raise StrictPreGapError("UNDECLARED_SOURCE_PRE_OPERAND")
    verified={}
    for symbol,entry in facts.items():
        if not isinstance(entry,dict) or entry.get("provenance")!="STRICT_PRE_OBSERVATION":
            raise StrictPreGapError("PRE_SYMBOL_PROVENANCE_INVALID")
        ts=entry.get("timestamp")
        value=entry.get("value")
        if (type(ts) is not int or ts>=at_ms or
            type(value) not in (int,float,bool) or
            not math.isfinite(float(value))):
            raise StrictPreGapError("STRICT_PRE_TIMESTAMP_OR_VALUE_INVALID")
        verified[symbol]=entry
    return verified


def analyze(profile:bytes, temporal:dict, *,
            synthetic_witnesses:dict|None=None,
            _synthetic_only:bool=False,
            early_window_ms:int=10000)->dict:
    """Analyze exact root call IDs, never optimistic native-return readiness.

    Synthetic witnesses are accepted ONLY for internal regression testing;
    real generation provides none until root-scoped PRE source instrumentation
    has passed a separate pinned C++ producer/validator contract.
    """
    if synthetic_witnesses is not None and not _synthetic_only:
        raise StrictPreGapError("UNVERIFIED_EXTERNAL_ROOT_PRE_PRODUCER_FORBIDDEN")
    if (type(early_window_ms) is not int or
        not 1<=early_window_ms<=120000):
        raise StrictPreGapError("INVALID_EARLY_SOURCE_SELECTION_WINDOW")
    if (temporal.get("schema")!=TEMPORAL_SCHEMA or
        temporal.get("product_policy_id")!=POLICY or
        temporal.get("source_profile_git_blob_sha1")!=git_blob(profile) or
        temporal.get("independent_FULL_READY_proven")!=0 or
        temporal.get("source_order_complete") is not False or
        temporal.get("priority_rule_optimality_proven") is not False or
        temporal.get("dummy_error_permitted") is not False or
        temporal.get("WCL_independent_blind_candidate_lock_maintained") is not True):
        raise StrictPreGapError("PINNED_SOURCE_TEMPORAL_PROVENANCE_REQUIRED")
    parsed=parse_profile(profile,require_source=False)
    lists=parsed["action_lists"]
    sweeps=temporal.get("observed_time_scoped_selection_frontiers")
    if not isinstance(sweeps,list) or not sweeps or len(sweeps)!=temporal.get("source_sweep_count"):
        raise StrictPreGapError("FULL_SOURCE_SWEEP_LEDGER_REQUIRED")
    first=min(s["at_simc_ms"] for s in sweeps)
    if type(first) is not int or first<0:
        raise StrictPreGapError("INVALID_SOURCE_TIME_ANCHOR")
    seen_sweep=set()
    seen_root=set()
    rows={}
    counters=Counter()
    requested=Counter()
    requests_by_symbol=defaultdict(lambda:{"roots":0,"earliest_at_ms":None})
    sample=[]
    unresolved=[]
    for sweep in sweeps:
        sid=sweep.get("sweep_call_id")
        parent=sweep.get("parent_sweep_call_id")
        at=sweep.get("at_simc_ms")
        owner=sweep.get("source_list")
        if (type(sid) is not int or sid<=0 or sid in seen_sweep or
            type(parent) is not int or parent<0 or
            (parent and parent not in seen_sweep) or
            type(at) is not int or at<first or
            owner not in lists or
            sweep.get("full_source_priority_frontier_closed") is not False or
            sweep.get("conditional_priority_verdict")!="UNKNOWN"):
            raise StrictPreGapError("SOURCE_SWEEP_IDENTITY_OR_PRIORITY_PROMOTION")
        seen_sweep.add(sid)
        phase=("EARLY_OBSERVED" if at-first<early_window_ms else "LATER_OBSERVED")
        events=sweep.get("observed_candidate_event_stream")
        if not isinstance(events,list):
            raise StrictPreGapError("MISSING_NATIVE_SOURCE_EVENT_STREAM")
        for event in events:
            if event.get("stage")!="ACTION_READY_CALLED":
                continue
            rid=event.get("original_action_ready_root_id")
            h=event.get("source_row_sha256")
            ordinal=event.get("ordinal_one_based")
            comparator=event.get("simc_NATIVE_return_post_comparator")
            if (type(rid) is not int or rid<=0 or rid in seen_root or
                type(ordinal) is not int or
                not 1<=ordinal<=len(lists[owner]) or
                not isinstance(h,str) or not HEX64.fullmatch(h) or
                type(comparator) is not bool or
                event.get("comparator_proves_independent_ready") is not False or
                event.get("physical_action_ready")!="UNKNOWN" or
                event.get("priority_verdict")!="UNKNOWN"):
                raise StrictPreGapError("ORIGINAL_NATIVE_ROOT_IDENTITY_NOT_CLOSED")
            row=lists[owner][ordinal-1]
            if (row["source_sha256"]!=h or
                row["action"]!=event.get("source_action")):
                raise StrictPreGapError("SOURCE_APL_ROOT_ROW_HASH_MISMATCH")
            seen_root.add(rid)
            counters["native_action_ready_root_calls"]+=1
            fields=row["expression_fields"]
            conditional=fields.get("if")
            if conditional is None:
                counters["source_if_absent"]+=1
                continue
            symbols=conditional["symbols"]
            for symbol in symbols:
                requested[symbol]+=1
                detail=requests_by_symbol[symbol]
                detail["roots"]+=1
                detail["earliest_at_ms"]=(
                    at if detail["earliest_at_ms"] is None
                    else min(detail["earliest_at_ms"],at))
            key=(owner,ordinal,h)
            if key not in rows:
                rows[key]={
                    "source_list":owner,
                    "ordinal_one_based":ordinal,
                    "source_row_sha256":h,
                    "source_action":row["action"],
                    "source_if_expression":conditional["source"],
                    "source_if_symbols":list(symbols),
                    "early_root_calls":0,
                    "later_root_calls":0,
                    "strict_PRE_positive_conditions":0,
                    "strict_PRE_negative_conditions":0,
                    "strict_PRE_UNKNOWN_conditions":0,
                    "static_syntax_determinate_conditions":0,
                    "readiness_still_UNKNOWN":True,
                    "priority_rule_still_UNKNOWN":True,
                }
            r=rows[key]
            r["early_root_calls" if phase=="EARLY_OBSERVED" else "later_root_calls"]+=1
            witness=None if synthetic_witnesses is None else synthetic_witnesses.get(rid)
            facts=({} if witness is None else
                   _trusted_root_facts(witness,root_id=rid,row_hash=h,
                                       at_ms=at,symbols=symbols))
            independently=evaluate_ast(
                conditional["ast"],facts,strict_pre=True,
                action_timestamp=at)
            as_bool=truth(independently)
            if as_bool is None:
                status=STATUS_UNKNOWN
                r["strict_PRE_UNKNOWN_conditions"]+=1
                counters["source_if_unknown"]+=1
            else:
                # A syntactically constant result needs no captured facts.
                # Fact-based results are restricted to internal synthetic
                # regressions until real root-identity PRE capture exists.
                static=evaluate_ast(conditional["ast"],{},strict_pre=True,
                                    action_timestamp=at)
                if truth(static) is not None:
                    status="SOURCE_AST_SYNTACTICALLY_DETERMINATE"
                    r["static_syntax_determinate_conditions"]+=1
                    counters["source_if_static_syntax_determinate"]+=1
                else:
                    if witness is None or not _synthetic_only:
                        raise StrictPreGapError("UNTRUSTED_PRE_FACT_PASSED_AST_PROOF")
                    status="SYNTHETIC_STRICT_PRE_AST_DETERMINATE_NOT_NATIVE"
                    counters["synthetic_strict_pre_ast_determinate"]+=1
                if as_bool:
                    r["strict_PRE_positive_conditions"]+=1
                else:
                    r["strict_PRE_negative_conditions"]+=1
            if len(sample)<16:
                sample.append({
                    "source_root_id":rid,"at_simc_ms":at,
                    "source_list":owner,"ordinal_one_based":ordinal,
                    "source_row_sha256":h,
                    "source_action":row["action"],
                    "source_if":conditional["source"],
                    "source_symbols":list(symbols),
                    "condition_status":status,
                    "condition_truth":("UNKNOWN" if as_bool is None else bool(as_bool)),
                    "native_action_ready_return_comparison_only":comparator,
                    "physical_ready":"UNKNOWN",
                    "source_priority":"UNKNOWN",
                })
            if status==STATUS_UNKNOWN:
                unresolved.append((phase,rid,at,owner,ordinal,h,row["action"],tuple(symbols)))
            counters["source_if_root_calls"]+=1
    if (len(seen_root)!=temporal.get("original_ready_calls") or
        len(seen_sweep)!=temporal.get("source_sweep_count") or
        counters["source_if_root_calls"]+counters["source_if_absent"]!=
            counters["native_action_ready_root_calls"]):
        raise StrictPreGapError("SOURCE_ROOT_COUNTS_NOT_RECONCILED")
    if (counters["source_if_unknown"]+
        counters["source_if_static_syntax_determinate"]+
        counters["synthetic_strict_pre_ast_determinate"]!=
        counters["source_if_root_calls"]):
        raise StrictPreGapError("SOURCE_AST_STATUS_ACCOUNTING_MISMATCH")
    ranked=sorted(
        ({"symbol":s,"observed_roots_requiring_symbol":n,
          "earliest_at_simc_ms":requests_by_symbol[s]["earliest_at_ms"],
          "verified_root_PRE_witnesses":0,
          "root_id_causal_link_available":False,
          "source_producer_semantics":"NOT_YET_VERIFIED"}
         for s,n in requested.items()),
        key=lambda x:(-x["observed_roots_requiring_symbol"],x["symbol"])
    )
    rows_out=[rows[k] for k in sorted(rows)]
    return {
        "schema":SCHEMA,"product_policy_id":POLICY,
        "source_profile_git_blob_sha1":git_blob(profile),
        "target_count":temporal["target_count"],
        "first_observed_selection_at_ms":first,
        "early_window_ms":early_window_ms,
        "exact_source_sweeps_checked":len(seen_sweep),
        "unique_action_ready_roots_checked":len(seen_root),
        "status_counts":dict(sorted(counters.items())),
        "unresolved_source_if_row_count":sum(
            r["strict_PRE_UNKNOWN_conditions"]>0 for r in rows_out),
        "source_if_condition_row_gaps":rows_out,
        "prioritized_root_PRE_operand_requirements":ranked,
        "root_PRE_requirement_top_12":ranked[:12],
        "first_bounded_IF_root_examples":sample,
        "missing_exact_source_root_witness_count":len(unresolved),
        "legacy_IF_receipt_missing_unique_current_root_ID":True,
        "legacy_timestamp_list_ordinal_name_join_forbidden":True,
        "root_PRE_producer_contract_verified":False,
        "actual_original_native_condition_truth_confirmed":False,
        "synthetic_witness_test_mode":_synthetic_only,
        "source_if_AST_syntax_only_truth_is_not_full_READY":True,
        "full_ready_proven":0,
        "source_priority_closed":False,
        "WCL_blind_discovery_semantics_injected":False,
        "dummy_error_permitted":False,
        "WCL_API_calls":0,
    }


def selftest():
    p=(b'warrior="Synthetic"\nspec=fury\n'
       b'actions=/foo,if=rage>50\n'
       b'actions+=/bar,if=active_enemies>=2\n'
       b'actions+=/baz,if=0|unknown\n'
       b'actions+=/free,if=1\n')
    actions=parse_profile(p,require_source=False)["action_lists"]["default"]
    def e(i,rid):
        row=actions[i]
        return {
            "stage":"ACTION_READY_CALLED",
            "original_action_ready_root_id":rid,
            "source_row_sha256":row["source_sha256"],
            "source_action":row["action"],
            "ordinal_one_based":i+1,
            "simc_NATIVE_return_post_comparator":False,
            "comparator_proves_independent_ready":False,
            "physical_action_ready":"UNKNOWN","priority_verdict":"UNKNOWN"}
    s={
        "schema":TEMPORAL_SCHEMA,"product_policy_id":POLICY,
        "source_profile_git_blob_sha1":git_blob(p),
        "target_count":1,
        "source_order_complete":False,
        "independent_FULL_READY_proven":0,
        "priority_rule_optimality_proven":False,
        "dummy_error_permitted":False,
        "WCL_independent_blind_candidate_lock_maintained":True,
        "source_sweep_count":1,
        "observed_time_scoped_selection_frontiers":[{
            "sweep_call_id":10,"parent_sweep_call_id":0,
            "at_simc_ms":100,"source_list":"default",
            "full_source_priority_frontier_closed":False,
            "conditional_priority_verdict":"UNKNOWN",
            "observed_candidate_event_stream":[e(0,11),e(1,12),e(2,13),e(3,14)]}],
        "original_ready_calls":4,
    }
    out=analyze(p,s)
    assert out["unique_action_ready_roots_checked"]==4
    assert out["status_counts"]["source_if_unknown"]==3
    assert out["status_counts"]["source_if_static_syntax_determinate"]==1
    assert out["full_ready_proven"]==0
    assert out["prioritized_root_PRE_operand_requirements"][0]["observed_roots_requiring_symbol"]==1
    import copy
    fact={"root_call_id":11,
          "source_row_sha256":actions[0]["source_sha256"],
          "action_at_simc_ms":100,
          "origin":"SYNTHETIC_SOURCE_ROOT_PRE_FIXTURE",
          "facts":{"rage":{"value":60,"timestamp":99,
                            "provenance":"STRICT_PRE_OBSERVATION"}}}
    synthetic=analyze(p,s,synthetic_witnesses={11:fact},_synthetic_only=True)
    assert synthetic["status_counts"]["synthetic_strict_pre_ast_determinate"]==1
    assert synthetic["status_counts"]["source_if_unknown"]==2
    for modified in (
        dict(fact,root_call_id=12),
        dict(fact,facts={"rage":{"value":60,"timestamp":100,
                                "provenance":"STRICT_PRE_OBSERVATION"}}),
        dict(fact,facts={"rage":{"value":60,"timestamp":101,
                                "provenance":"STRICT_PRE_OBSERVATION"}}),
        dict(fact,source_row_sha256="0"*64),
        dict(fact,facts={"rage":{"value":60,"timestamp":99,
                                "provenance":"UNTRUSTED"}}),
    ):
        try:analyze(p,s,synthetic_witnesses={11:modified},_synthetic_only=True)
        except StrictPreGapError:pass
        else:raise AssertionError("NONSTRICT_ROOT_PRE_ACCEPTED")
    try:analyze(p,s,synthetic_witnesses={11:fact})
    except StrictPreGapError:pass
    else:raise AssertionError("UNVERIFIED_REAL_PRE_PRODUCER_ACCEPTED")
    corrupted=copy.deepcopy(s)
    corrupted["observed_time_scoped_selection_frontiers"][0][
        "observed_candidate_event_stream"][1]["original_action_ready_root_id"]=11
    try:analyze(p,corrupted)
    except StrictPreGapError:pass
    else:raise AssertionError("DUPLICATE_ROOT_ACCEPTED")
    return {
        "schema":SCHEMA,"status":"PASS_OFFLINE_SYNTHETIC",
        "checks":15,"strict_pre_timestamp_lt_action_enforced":True,
        "synthetic_root_if_AST_determinate":1,
        "real_native_root_PRE_captured":False,
        "positive_full_READY_proven":0,"WCL_API_calls":0
    }


def compare(st:dict,two:dict)->dict:
    if (st.get("schema")!=SCHEMA or two.get("schema")!=SCHEMA or
        st.get("product_policy_id")!=POLICY or two.get("product_policy_id")!=POLICY or
        st.get("source_profile_git_blob_sha1")!=two.get("source_profile_git_blob_sha1") or
        st.get("target_count")!=1 or two.get("target_count")!=2 or
        st.get("root_PRE_producer_contract_verified") is not False or
        two.get("root_PRE_producer_contract_verified") is not False or
        st.get("full_ready_proven")!=0 or two.get("full_ready_proven")!=0):
        raise StrictPreGapError("INVALID_CROSS_TARGET_PRE_GAP_COMPARISON")
    ranks=[]
    for label,data in (("ST",st),("TWO_TARGET",two)):
        for x in data["prioritized_root_PRE_operand_requirements"]:
            ranks.append((label,x["symbol"],x["observed_roots_requiring_symbol"]))
    merged=defaultdict(lambda:{"ST":0,"TWO_TARGET":0})
    for target,sym,count in ranks:merged[sym][target]=count
    combined=sorted(
        ({"symbol":sym,"ST_observed_roots":v["ST"],
          "two_target_observed_roots":v["TWO_TARGET"],
          "combined_observed_roots":v["ST"]+v["TWO_TARGET"],
          "independent_source_PRE_truth_coverage":0}
         for sym,v in merged.items()),
        key=lambda x:(-x["combined_observed_roots"],x["symbol"]))
    return {
        "schema":SCHEMA_RECEIPT,
        "source_profile_git_blob_sha1":st["source_profile_git_blob_sha1"],
        "ST_unresolved_source_if_calls":st["status_counts"].get("source_if_unknown",0),
        "two_target_unresolved_source_if_calls":two["status_counts"].get("source_if_unknown",0),
        "root_PRE_operand_capture_impact_ranked":combined,
        "top_12_source_PRE_symbols":combined[:12],
        "independent_root_condition_proofs":0,
        "target_count_switch_threshold_proven":False,
        "WCL_blind_candidate_lock_done":False,
        "source_order_complete":False,"WCL_API_calls":0
    }


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--profile",type=Path)
    p.add_argument("--st-time-ir",type=Path)
    p.add_argument("--two-target-time-ir",type=Path)
    p.add_argument("--out-dir",type=Path)
    p.add_argument("--early-window-ms",type=int,default=10000)
    a=p.parse_args()
    needed=(a.profile,a.st_time_ir,a.two_target_time_ir,a.out_dir)
    if all(x is None for x in needed):
        print(canonical(selftest()).decode(),end="")
    elif all(x is not None for x in needed):
        profile=a.profile.read_bytes()
        st=analyze(profile,json.loads(a.st_time_ir.read_bytes()),
                   early_window_ms=a.early_window_ms)
        two=analyze(profile,json.loads(a.two_target_time_ir.read_bytes()),
                    early_window_ms=a.early_window_ms)
        diff=compare(st,two)
        a.out_dir.mkdir(parents=True,exist_ok=True)
        for name,r in (("st",st),("2t",two),("st2t_pre_requirements",diff)):
            with (a.out_dir/(name+".json")).open("xb") as out:
                out.write(canonical(r))
        print(canonical({
            "schema":SCHEMA,"status":"REAL_NATIVE_PRE_GAP_REPLAY_PASS",
            "ST_root_calls":st["unique_action_ready_roots_checked"],
            "two_target_root_calls":two["unique_action_ready_roots_checked"],
            "source_strict_PRE_witnesses_reused":0,
            "root_PRE_symbol_requirements":len(diff["root_PRE_operand_capture_impact_ranked"]),
            "independent_full_READY_proven":0,"WCL_API_calls":0
        }).decode(),end="")
    else:p.error("provide profile, both source IRs and output dir together")


if __name__=="__main__":
    main()
